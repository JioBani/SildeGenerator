import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {dirname,resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..'),dir=join(root,'experiments/actor-binding');
const source=join(root,'experiments/actor-performance/output/standard-actor-v3'),out=join(dir,'output');mkdirSync(out,{recursive:true});
const sha=v=>createHash('sha256').update(v).digest('hex');
const manifest=JSON.parse(readFileSync(join(source,'manifest.json'),'utf8')),context=vm.createContext({});
vm.runInContext(readFileSync(join(dir,'rig.js'),'utf8'),context);context.AstraActorRig.load(manifest);
for(const part of manifest.parts)assert.equal(sha(readFileSync(join(source,part.path))),part.sha256);
for(const [p,h]of Object.entries(manifest.source_hashes))assert.equal(sha(readFileSync(join(root,'experiments/actor-performance',p))),h);
const svg=readFileSync(join(source,'assembled.svg'),'utf8');assert.equal(sha(svg),manifest.assembly.rebuilt_sha256);
const audit=JSON.parse(readFileSync(join(source,'playback-audit.json'),'utf8'));
assert.equal(audit.asset_manifest_sha256,sha(readFileSync(join(source,'manifest.json'))));
const data={svg,manifest,assembly_sha256:sha(svg),manifest_sha256:audit.asset_manifest_sha256,production_ready:false};
writeFileSync(join(out,'actor-data.js'),'window.PortableActorData='+JSON.stringify(data)+';');
console.log(JSON.stringify({actor:manifest.spec.actor_id,output:out,production_ready:false}));
